from fastapi import APIRouter, Query, HTTPException, Depends
from typing import Optional, List
from sqlalchemy.orm import Session
from app.services.alert_engine import alert_engine
from app.models.schemas import Alert
from app.database import get_db

router = APIRouter(prefix="/api/alerts", tags=["Alerts"])

@router.get("", response_model=List[Alert])
def get_alerts(
    provider: Optional[str] = Query(None, description="Filter by provider: aws, azure, or gcp"),
    severity: Optional[str] = Query(None, description="Filter by severity: critical, warning, or info"),
    acknowledged: Optional[bool] = Query(None, description="Filter by acknowledgment state"),
    db: Session = Depends(get_db),
):
    """
    Returns active and historical alerts generated by the alert rule engine.
    Supports filtering by provider, severity level, and acknowledgment status.
    """
    # Evaluate rules on demand to ensure fresh triggers
    alert_engine.evaluate_rules(db=db)
    return alert_engine.get_alerts(provider=provider, severity=severity, acknowledged=acknowledged)

@router.post("/{alert_id}/acknowledge")
def acknowledge_alert(alert_id: str, db: Session = Depends(get_db)):
    """
    Marks an alert as acknowledged by the operator.
    """
    success = alert_engine.acknowledge_alert(alert_id, db=db)
    if not success:
        raise HTTPException(status_code=404, detail=f"Alert with ID '{alert_id}' not found.")
    return {"status": "success", "alert_id": alert_id, "acknowledged": True}
